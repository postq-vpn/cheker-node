#!/bin/bash
# TITLE: Серверы флота онлайн
# Виджет показывает, сколько серверов из базы Скайнета отвечает прямо сейчас:
# "Флот онлайн: 5 из 7". Зелёный — отвечают все, жёлтый — часть, красный — никто.
#
# Проверяем ОТКРЫТЫЙ SSH-ПОРТ, а не вход по ключу. Виджет пересобирается
# в фоне раз в минуту, и полный SSH-хендшейк по всему флоту с такой частотой —
# это и лишняя нагрузка, и строчка в auth.log каждого сервера каждую минуту.
# Меню флота проверяет именно вход по ключу, поэтому сервер с живым портом,
# но битым ключом там покажет OFF, а здесь попадёт в онлайн. Если нужно
# ровно то же число, что в меню, — переключи CHECK_MODE на "ssh".
#
# Локальную машину не считаем: в базе только удалённые серверы.
#
# КАК НАСТРОИТЬ ПОД СЕБЯ:
#   - CHECK_MODE="ssh" — считать онлайн только те серверы, куда реально пускает
#     ключ. Медленнее и шумит в логах серверов, зато совпадает с меню флота.
#   - TIMEOUT — сколько секунд ждать ответа. Меньше 2 не стоит: далёкие сервера
#     начнут мигать в статусе.
#   - Лейбл "Флот онлайн" можно переименовать, главное оставить двоеточие.

CHECK_MODE="port"
TIMEOUT=2

# База флота — тот же файл, что и у Решалы (config/reshala.conf). Виджет
# запускается отдельным процессом, переменные Решалы ему не видны, поэтому
# путь берём из окружения, только если он там оказался, а иначе — из HOME.
FLEET_DB="${FLEET_DATABASE_FILE:-$HOME/.reshala_fleet}"

# Нет базы или она пуста — значит флота нет, и виджету нечего показывать.
# Молчим, а не пишем "0 из 0": на одиночном сервере это была бы строка-шум.
[ -s "$FLEET_DB" ] || exit 0

tmp_dir=$(mktemp -d 2>/dev/null) || exit 0
total=0

# Опрашиваем серверы параллельно: последовательно весь флот упёрся бы
# в TIMEOUT на каждом мёртвом сервере.
while IFS='|' read -r name user ip port key_path sudo_pass category; do
    [ -n "$ip" ] || continue
    total=$((total + 1))
    (
        if [ "$CHECK_MODE" = "ssh" ]; then
            if timeout "$TIMEOUT" ssh -n -q -F /dev/null -o IdentitiesOnly=yes \
                -o BatchMode=yes -o ConnectTimeout="$TIMEOUT" \
                -o StrictHostKeyChecking=accept-new \
                -i "$key_path" -p "${port:-22}" "${user:-root}@${ip}" exit >/dev/null 2>&1; then
                echo "ON"
            fi
        else
            # IP и порт уезжают аргументами, а не подстановкой в текст команды:
            # база флота правится руками ([m] в меню флота), и строка оттуда
            # не должна уметь выполнить что-то своё.
            if timeout "$TIMEOUT" bash -c 'exec 3<>/dev/tcp/"$1"/"$2"' _ "$ip" "${port:-22}" 2>/dev/null; then
                echo "ON"
            fi
        fi
    ) > "$tmp_dir/$total" 2>/dev/null &
done < <(grep . "$FLEET_DB" 2>/dev/null)

wait

online=$(cat "$tmp_dir"/* 2>/dev/null | grep -c '^ON$')
rm -rf -- "$tmp_dir"

[ "$total" -gt 0 ] || exit 0

if [ "$online" -eq "$total" ]; then
    color='\033[0;32m'   # все на месте
elif [ "$online" -eq 0 ]; then
    color='\033[0;31m'   # не отвечает никто
else
    color='\033[1;33m'   # часть флота молчит
fi

# Цвет печатаем настоящим символом ESC (через %b), а не строкой "\033[...":
# дашборд прогоняет значение виджета через xargs, и там литеральный обратный
# слэш съедается — на экран уехало бы "033[0;32m5 из 7".
printf 'Флот онлайн: %b%s из %s%b\n' "$color" "$online" "$total" '\033[0m'
