#!/bin/bash
# TITLE: Инфра — статус ТСПУ
# Виджет показывает статус серверов категории "Инфра" из базы флота по
# данным ПОСЛЕДНЕЙ проверки ТСПУ (Skynet -> [t] "Отчёт «Блокировка ТСПУ»").
#
# Виджет НЕ бьёт зондами RIPE Atlas сам — только читает файл, который
# сохраняет modules/skynet/censorcheck_report.sh после каждого прогона
# (ручного или по расписанию cron). Сам замер платный и идёт максимум
# несколько раз в день, а этот виджет дашборд пересобирает раз в минуту —
# гонять зонды с такой частотой нельзя ни по деньгам, ни по здравому смыслу.
#
# Если проверка ТСПУ ни разу не запускалась (нет файла) или в базе флота
# нет серверов категории "Инфра" — виджету нечего показывать, молчим,
# как и 04_fleet_online.sh на пустой базе.
#
# Формат:
#   - все инфра-серверы доступны:      "Инфра: все доступны"
#   - есть недоступные/непроверенные:  "Инфра: доступно 2"
#                                       "<имя сервера>: недоступен"
#                                       "<имя сервера>: требует проверки"

STATE_FILE="/etc/reshala/tspu_infra.state"

[ -s "$STATE_FILE" ] || exit 0

ts="" ok=0 blocked=0 skip=0

while IFS='=' read -r key val; do
    case "$key" in
        TS) ts="$val" ;;
        OK) ok="$val" ;;
        BLOCKED) blocked="$val" ;;
        SKIP) skip="$val" ;;
    esac
done < <(grep -E '^(TS|OK|BLOCKED|SKIP)=' "$STATE_FILE")

# Цвет печатаем настоящим ESC-символом через %b (не строкой "\033[...") —
# дашборд прогоняет значение виджета через xargs, и литеральный обратный
# слэш там съедается (см. этот же приём в 04_fleet_online.sh).
if [ "$blocked" -eq 0 ] && [ "$skip" -eq 0 ]; then
    printf 'Инфра: %bвсе доступны%b (%s)\n' '\033[0;32m' '\033[0m' "$ts"
    exit 0
fi

if [ "$blocked" -gt 0 ]; then
    color='\033[0;31m'
else
    color='\033[1;33m'
fi

printf 'Инфра: %bдоступно %s%b (%s)\n' "$color" "$ok" '\033[0m' "$ts"

# Проблемные серверы — каждый своей строкой "<имя>: <статус>", чтобы на
# дашборде сразу было видно, КТО именно недоступен, без похода в Telegram.
while IFS='|' read -r name kind; do
    [ -n "$name" ] || continue
    case "$kind" in
        BLOCKED)
            printf '%s: %bнедоступен%b\n' "$name" '\033[0;31m' '\033[0m'
            ;;
        SKIP)
            printf '%s: %bтребует проверки%b\n' "$name" '\033[1;33m' '\033[0m'
            ;;
    esac
done < <(grep '|' "$STATE_FILE")
